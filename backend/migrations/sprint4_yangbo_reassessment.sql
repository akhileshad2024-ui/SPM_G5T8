-- Does not change event fields/statuses, stock holds or attendee registrations.
BEGIN;
CREATE TABLE IF NOT EXISTS arrangement_reassessments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id integer NOT NULL REFERENCES events(id),
    source varchar NOT NULL,
    source_id integer NOT NULL,
    target_type varchar NOT NULL,
    target_id integer NOT NULL,
    reason text NOT NULL,
    context json NOT NULL DEFAULT '{}',
    created_at timestamptz NOT NULL,
    resolved_at timestamptz,
    resolved_by_id integer REFERENCES users(id),
    resolution text,
    CONSTRAINT uq_reassessment_source_target UNIQUE (event_id, source, source_id, target_type, target_id)
);
CREATE INDEX IF NOT EXISTS ix_arrangement_reassessments_event_id ON arrangement_reassessments(event_id);
CREATE TABLE IF NOT EXISTS event_preparations (
    event_id integer PRIMARY KEY REFERENCES events(id),
    safety_review_id integer NOT NULL REFERENCES safety_reviews(id),
    started_by_id integer NOT NULL REFERENCES users(id),
    started_at timestamptz NOT NULL
);
ALTER TABLE arrangement_reassessments ENABLE ROW LEVEL SECURITY;
ALTER TABLE event_preparations ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON arrangement_reassessments, event_preparations FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE arrangement_reassessments_id_seq FROM PUBLIC, anon, authenticated;
GRANT ALL ON arrangement_reassessments, event_preparations TO service_role;
GRANT ALL ON SEQUENCE arrangement_reassessments_id_seq TO service_role;
COMMIT;
